/**
 * Pitch accuracy on real singing with a human-annotated reference f0.
 *
 *   npm run eval:f0 -- <folder> [--name "vocadito"]
 *
 * The folder holds WAV files and, for each, a reference f0 file with the
 * same name (see eval/referenceF0.ts). Recommended dataset: vocadito
 * (40 solo singers, f0 annotated by musicians, CC BY 4.0):
 * https://zenodo.org/record/5578807 . Datasets are not committed to this
 * repository; keep them in eval/datasets/ (ignored by git).
 *
 * Writes eval/results/real-voice-pitch.md.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { evaluateClip, findPairs } from "./referenceF0";
import { median } from "./metrics";

const args = process.argv.slice(2);
const dir = args.find(a => !a.startsWith("--"));
const nameIdx = args.indexOf("--name");
const name = nameIdx >= 0 ? args[nameIdx + 1] : dir;
if (!dir) {
  console.log("Usage: npm run eval:f0 -- <folder with WAV + reference f0 files> [--name dataset-name]");
  process.exit(1);
}

const pairs = findPairs(dir);
if (pairs.length === 0) {
  console.log(`No WAV files with a matching reference f0 file were found in ${dir}.`);
  process.exit(1);
}

const results = pairs.map(p => {
  process.stdout.write(`  ${p.wav} ... `);
  const r = evaluateClip(p.wav, readFileSync(p.ref, "utf8"));
  console.log(`MPM ${r.mpm.rpa20.toFixed(1)}% within 20 cents`);
  return r;
});

const pool = (k: "mpm" | "yin") => {
  const voiced = results.reduce((a, r) => a + r[k].voicedFrames, 0);
  const unvoiced = results.reduce((a, r) => a + r[k].unvoicedFrames, 0);
  const w = (f: (s: (typeof results)[0]["mpm"]) => number, by: "voicedFrames" | "unvoicedFrames") => {
    const tot = by === "voicedFrames" ? voiced : unvoiced;
    return tot ? results.reduce((a, r) => a + (Number.isNaN(f(r[k])) ? 0 : f(r[k]) * r[k][by]), 0) / tot : NaN;
  };
  return {
    rpa20: w(s => s.rpa20, "voicedFrames"), rpa50: w(s => s.rpa50, "voicedFrames"),
    octave: w(s => s.octaveErrors, "voicedFrames"), recall: w(s => s.voicingRecall, "voicedFrames"),
    fa: w(s => s.voicingFalseAlarm, "unvoicedFrames"),
    med: median(results.flatMap(r => r[k].absErrors)),
  };
};
const m = pool("mpm"), y = pool("yin");
const secs = results.reduce((a, r) => a + r.seconds, 0);
const f = (x: number) => (Number.isNaN(x) ? "–" : x.toFixed(1));

const md = `# Pitch accuracy on real singing

Dataset: ${name}, ${results.length} recordings, ${(secs / 60).toFixed(1)} minutes.
Reference: f0 annotated by people, compared frame by frame (10 ms). Frames at the
edge of a note (where the reference changes between sung and silent) are not scored.

| Detector | Within 20 cents | Within 50 cents | Octave errors | Sung frames with a pitch | Pitch reported in silence | Median error |
|---|---|---|---|---|---|---|
| MPM (used by the app) | ${f(m.rpa20)}% | ${f(m.rpa50)}% | ${f(m.octave)}% | ${f(m.recall)}% | ${f(m.fa)}% | ${f(m.med)} cents |
| YIN (for comparison) | ${f(y.rpa20)}% | ${f(y.rpa50)}% | ${f(y.octave)}% | ${f(y.recall)}% | ${f(y.fa)}% | ${f(y.med)} cents |

"Within 20 cents" counts every sung frame, including ones where the app reported no
pitch, so it already includes missed frames.

## Per recording (MPM)

| Recording | Seconds | Within 20 cents | Within 50 cents | Sung frames with a pitch | Pitch in silence |
|---|---|---|---|---|---|
${results.map(r => `| ${r.file} | ${r.seconds.toFixed(1)} | ${f(r.mpm.rpa20)}% | ${f(r.mpm.rpa50)}% | ${f(r.mpm.voicingRecall)}% | ${f(r.mpm.voicingFalseAlarm)}% |`).join("\n")}

Generated by \`npm run eval:f0\` on ${new Date().toISOString().slice(0, 10)}.
`;
mkdirSync("eval/results", { recursive: true });
writeFileSync("eval/results/real-voice-pitch.md", md);
console.log(`\nMPM: ${f(m.rpa20)}% within 20 cents, ${f(m.rpa50)}% within 50 cents (YIN ${f(y.rpa20)}% / ${f(y.rpa50)}%).`);
console.log("Wrote eval/results/real-voice-pitch.md");
